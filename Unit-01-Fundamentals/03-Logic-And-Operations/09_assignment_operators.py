# Python Assignment Operators

x = 10

# 1. Assignment (=)
x = 10
print("x =", x)

# 2. Addition Assignment (+=)
x += 5
print("x += 5:", x)

# 3. Subtraction Assignment (-=)
x -= 3
print("x -= 3:", x)

# 4. Multiplication Assignment (*=)
x *= 2
print("x *= 2:", x)

# 5. Division Assignment (/=)
x /= 4
print("x /= 4:", x)

# 6. Floor Division Assignment (//=)
x //= 2
print("x //= 2:", x)

# 7. Modulus Assignment (%=)
x %= 3
print("x %= 3:", x)

# 8. Exponent Assignment (**=)
x **= 2
print("x **= 2:", x)
