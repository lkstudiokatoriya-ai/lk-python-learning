# A while loop repeatedly executes a block of code
# as long as the given condition is True.

# Start value
number = 1

# The loop continues while number is less than or equal to 10
while number <= 10:
    print(number)

    # Increase the value so that the loop can eventually stop
    number += 1

print("Loop completed.")