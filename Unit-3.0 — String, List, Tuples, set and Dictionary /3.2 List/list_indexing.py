# list_indexing.py

numbers = [10, 20, 30, 40, 50]

# Positive indexing
print(numbers[0])
print(numbers[1])
print(numbers[2])
print(numbers[3])
print(numbers[4])


# Negative indexing
print(numbers[-1])
print(numbers[-2])
print(numbers[-3])


# Indexing with strings
subjects = ["Python", "Circuit", "Machines", "Power"]

print(subjects[0])
print(subjects[2])
print(subjects[-1])


# Changing an element using index
numbers[2] = 35

print(numbers)