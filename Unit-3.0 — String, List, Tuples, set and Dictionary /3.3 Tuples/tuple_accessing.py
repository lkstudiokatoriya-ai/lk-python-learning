# tuple_accessing.py

numbers = (10, 20, 30, 40, 50)

# Positive indexing
print(numbers[0])
print(numbers[2])
print(numbers[4])

# Negative indexing
print(numbers[-1])
print(numbers[-2])
print(numbers[-5])

