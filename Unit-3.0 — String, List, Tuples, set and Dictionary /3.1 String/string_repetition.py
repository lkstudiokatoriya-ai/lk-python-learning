# string_repetition.py

# Repeating a string
text = "Python "

print(text * 3)


# Repeating a character
symbol = "*"

print(symbol * 10)


# Repeating a string using a variable
name = "Lalan "

times = 3

print(name * times)


# Repetition with user input
text = input("Enter a string: ")
times = int(input("Enter repetition count: "))

print(text * times)