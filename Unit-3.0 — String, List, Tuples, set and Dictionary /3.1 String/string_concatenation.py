# string_concatenation.py

# Concatenation using +
first_name = "Lalan"
last_name = "Kumar"

full_name = first_name + " " + last_name

print(full_name)


# Concatenating multiple strings
a = "Python"
b = "Programming"

result = a + " " + b

print(result)


# Concatenation with user input
first = input("Enter first name: ")
last = input("Enter last name: ")

print(first + " " + last)